import assert from 'node:assert/strict';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import test from 'node:test';
import {openChromium, until} from './offline-chromium.mjs';
import {linkFixture, offlineProviders} from './offline-providers.mjs';
import {listen, stop, testSite} from './offline-site.mjs';
import {readCsv} from '../dist/csv.js';

test('An old Upcoming bookmark and multiple profiles preserve Watchlist, Dropped and Pick Up choices', {timeout:180_000}, async t => {
  const {server} = await testSite();
  const origin = 'http://127.0.0.1:' + await listen(server);
  const providers = offlineProviders(origin);
  await providers.settings({tmdb_key:'fictional-offline-key'});
  await providers.upload('lists.csv','list,show_id,show\r\nFollowing upcoming,45,The Listening House\r\nFavourites,45,The Listening House\r\n');
  const profiles = [];
  let browser;
  t.after(async () => {
    try { await browser?.close(); } finally {
      await stop(server);
      for (const profile of profiles) await rm(profile,{recursive:true,force:true,maxRetries:6,retryDelay:150});
    }
  });
  async function freshProfile() {
    const profile = await mkdtemp(join(tmpdir(),'csvtv-follow-upcoming-'));
    profiles.push(profile);
    browser = await openChromium(profile,providers.respond);
    await linkFixture(browser,origin);
    await visit('upcoming');
    await browser.waitFor('document.querySelector(".sync-state")?.dataset.synced === "true"');
  }
  const visit = route => browser.navigate(origin + '/tracker/#/' + route);
  const row = 'document.querySelector(\'.watchlist-screen a[href="#/show/45"]\')';
  const toggle = '.show-watchlist';
  const button = 'document.querySelector(".show-watchlist")?.textContent';
  const lists = () => readCsv('lists',providers.files.get('/lists.csv').bytes).rows.map(r => r.list);
  await freshProfile();
  await browser.waitFor(row);
  await browser.click('.watchlist-screen .watch-rows a');
  await browser.click('.show-more');
  await browser.waitFor('[...document.querySelectorAll("dialog button")].find(b=>b.textContent==="Remove from Watchlist")');
  await browser.evaluate('[...document.querySelectorAll("dialog button")].find(b=>b.textContent==="Remove from Watchlist").focus()');
  await browser.press('Space');
  await browser.waitFor(button + ' === "Add to Watchlist"');
  await until(() => lists().includes('Hidden from upcoming'),'unfollow uploaded');
  assert.deepEqual(lists().sort(), ['Favorites','Hidden from upcoming']);
  await browser.close(); browser = undefined;
  await freshProfile();
  await browser.waitFor('document.querySelector(".watchlist-screen")?.textContent.includes("Your Watchlist is empty.")');
  assert.equal(await browser.evaluate('!!' + row),false);
  await visit('show/45');
  await browser.waitFor(button + ' === "Add to Watchlist"');
  await browser.click(toggle);
  await browser.waitFor('!document.querySelector(".show-watchlist") && document.querySelector(".show-more")');
  await until(() => !lists().includes('Hidden from upcoming'),'follow uploaded');
  assert.deepEqual(lists().sort(), ['Favorites','Watchlist']);
  await visit('watchlist');
  await browser.waitFor('document.querySelector(\'[data-section="available"] a[href="#/show/45"]\')');
  await visit('lists');
  await browser.waitFor('document.querySelector("#chosen-list")?.textContent === "Favorites"');
  assert.equal(await browser.evaluate('Array.from(document.querySelectorAll("[data-list-focus]")).some(n=>n.dataset.listFocus==="chip/Watchlist")'),false);
  await browser.close(); browser = undefined;
  await freshProfile();
  await browser.waitFor(row);
  await browser.click('.watchlist-screen .watch-rows a');
  await browser.waitFor('document.querySelector(".show-drop")?.textContent === "Drop"');
  await browser.waitFor('document.querySelector(".show-actions .primary")');
  await browser.evaluate('document.querySelector(".show-actions .primary").focus()');
  await browser.press('Tab');
  assert.equal(await browser.evaluate('document.activeElement === document.querySelector(".show-drop")'),true);
  await browser.press('Tab');
  assert.equal(await browser.evaluate('document.activeElement === document.querySelector(".show-list")'),true);
  await browser.press('Tab',{shift:true});
  await browser.press('Enter');
  await browser.waitFor('document.querySelector(".show-drop")?.textContent === "Pick Up"');
  await until(() => lists().includes('Dropped'),'dropped status uploaded');
  assert.deepEqual(lists().sort(), ['Dropped','Favorites','Watchlist']);
  await browser.close(); browser = undefined;
  await freshProfile();
  await browser.waitFor('document.querySelector(".watchlist-screen")?.textContent.includes("Your Watchlist is empty.")');
  assert.equal(await browser.evaluate('!!' + row),false);
  await visit('library');
  await browser.click('[data-filter=dropped]');
  await browser.click('.library-grid a[href="#/show/45"]');
  await browser.waitFor('document.querySelector(".show-drop")?.textContent === "Pick Up"');
  await browser.click('.show-drop');
  await until(() => lists().includes('csvTV: picked up'),'Pick Up uploaded');
  assert.deepEqual(lists().sort(), ['Favorites','Watchlist','csvTV: picked up']);
  await visit('watchlist');
  await browser.waitFor(row);
});
